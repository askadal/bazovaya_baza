const norm=s=>(s||'').toLowerCase().replace(/ё/g,'е');
export function sportType(p){
 const n=norm(p.name),s=norm(p.sourceCategory),text=n+' '+s,head=n.split(/\s(?:с|со|для|из|на|под|без)\s/)[0];
 if(p.manufacturerId==='kenguru'&&/канатные игровые комплексы/.test(s))return {section:'Детское оборудование',category:'Лазалки и скалодромы'};
 const sourceSport=/спортив|воркаут|workout|тренажер|паркур/.test(s);
 const obvious=/баскетбол|теннис|текбол|турник|брусь|рукоход|шведск.*стен|скалодром|боксерск|футбольн.*ворот/.test(head);
 if(p.section!=='Спортивное оборудование'&&!(sourceSport&&obvious))return null;
 const result=category=>({section:'Спортивное оборудование',category});
 if(/информационн|информационый|информационная|информационное|инфостенд|табличк|^зеркало|йог/.test(n)&&!/комплекс|площадка/.test(n))return {section:'Городская мебель',category:/зеркало/.test(n)?'Другое':'Навигация'};
 if(/трибун/.test(n))return {section:'Городская мебель',category:'Амфитеатры'};
 if(/шахмат|гамбит|^сиденье|стол.*без шахмат/.test(text))return {section:'Городская мебель',category:/^сиденье/.test(n)?'Кресла и стулья':'Столы'};
 if(/паркур|parkour/.test(text))return result('Паркур');
 if(/спортивный кластер|воркаут.площадка|воркаут\/workout площадка|спортивная площадка|^арена|футбольная (?:площадка|арена)|^поле для|универсальная спортивная арена|^парк [smlм]\b/.test(n))return result('Готовые спортивные площадки');
 // Names describe the actual element before broad manufacturer sections such as «Тренажеры».
 if(/теннис|текбол|панна|футбол|волейбол|бадминтон|хоккей|гольф/.test(n+' '+s.split('/').pop())&&!/баскетбол/.test(n))return result('Игровое спортивное оборудование');
 if(/баскетбол/.test(n)&&/ворот|футбол|мульти|арена|поле/.test(n))return result('Игровое спортивное оборудование');
 if(/кольц.*(?:для игр|мяч)|теннис|текбол/.test(n))return result('Игровое спортивное оборудование');
 const types=[];
 if(/баскетбол/.test(n))types.push('Игровое спортивное оборудование');
 if(/турник|перекладин/.test(n))types.push('Турники');
 if(/брусь|паралет|поручн.*отжим|стойк.*отжим/.test(n))types.push('Брусья');
 if(/шведск.*стен|шведск.*лестниц/.test(n))types.push('Шведская стенка');
 if(/рукоход|monkey bars/.test(n))types.push(/молоток/.test(n)?'Рукоход-молоток':/змеевик|змейк/.test(n)?'Рукоход-змеевик':'Рукоход');
 if(/кольц/.test(n)&&!/баскетбол/.test(n)&&!/кольцевая|кольцо для рук|тренажер.кольцо/.test(n))types.push('Кольца');
 if(/скалодром|скалолаз|боулдер|булдер/.test(n))types.push('Скалодром');
 if(/(?:скам|скаме|доска|стенд|станок).*(?:пресс|наклон|гимнаст)|(?:пресс).*(?:скам|леж)|гимнастические скам|наклонная доска|наклонн.*скам|скам.*углов|скам.*регулируем|лавочк.*пресс/.test(n))types.push('Наклонная скамья');
 if(/боксер|(?:^|\s)бокс(?:\s|$)|для бокса|мешок|груша/.test(n))types.push('Боксерский мешок');
 if(/канат/.test(n))types.push('Канат');
 if(types.length>1)return result('Воркаут-комплексы');
 if(types.length===1)return result(types[0]);
 if(/комплекс|станция|рама/.test(n))return result(/воркаут|workout|кроссфит/.test(text)?'Воркаут-комплексы':'Спортивные комплексы');
 const leaf=s.split('/').pop();
 if(/баскетбол/.test(leaf))return result('Игровое спортивное оборудование');
 if(/рукоход/.test(leaf))return result(/молоток/.test(leaf)?'Рукоход-молоток':/змеевик/.test(leaf)?'Рукоход-змеевик':'Рукоход');
 if(/турник/.test(leaf))return result('Турники');
 if(/брусь|отжимани/.test(leaf))return result('Брусья');
 if(/шведск/.test(leaf))return result('Шведская стенка');
 if(/скамьи|скамьи для пресса/.test(leaf))return result('Наклонная скамья');
 if(/скалолаз|скалодром/.test(leaf))return result('Скалодром');
 if(/бокс/.test(leaf))return result('Боксерский мешок');
 if(/гиперэкстензия|вертикальный пресс|^становая тяга/.test(n))return result('Уличные тренажеры');
 if(/комплекс|станция|рама|полоса препятств|баланс|бревно|переправ|стенка|лабиринт|пенек|пеньк|переход|препятств|лиана|бум|настил|ступен|упор/.test(n))return result('Игровое спортивное оборудование');
 if(/тренажер|силовые тренаж|фитнес/.test(n+' '+leaf)&&!/воркаут|workout/.test(s))return result('Уличные тренажеры');
 return result('Спортивные элементы');
}

